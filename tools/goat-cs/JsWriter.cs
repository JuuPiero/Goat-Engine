// C# syntax (+ semantic model) → JavaScript text.
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace GoatCs;

public class JsWriter(SemanticModel model, string fileStem)
{
    readonly StringBuilder sb = new();
    int indent;

    static readonly Dictionary<string, string> Lifecycle = new()
    {
        ["Awake"] = "awake", ["Start"] = "start", ["Update"] = "update", ["FixedUpdate"] = "fixedUpdate",
        ["LateUpdate"] = "lateUpdate", ["OnDestroy"] = "onDestroy",
    };
    // engine members whose JS name isn't just camelCase
    static readonly Dictionary<string, string> Renames = new()
    {
        ["Debug.LogWarning"] = "warn", ["Debug.LogError"] = "error",
    };
    const string Exports = "Behaviour, MonoBehaviour, Vector2, Vector3, Quaternion, Transform, GameObject, Time, Input, Debug, Mathf, Application, WaitForSeconds, WaitForSecondsRealtime, WaitUntil, WaitWhile, WaitForEndOfFrame, WaitForFixedUpdate, Awaitable, DOTween, Ease, LoopType, PathType, Tween, Sequence, PlayerPrefs, SaveData, UI, Physics, Physics2D, Audio, AudioSource, AudioMixer, Animator, SpriteAnimator, NavMeshAgent, NavMesh";

    // ------------------------------------------------------------------ output helpers
    void Line(string s) => sb.Append(new string(' ', indent * 2)).Append(s).Append('\n');

    public string File(CompilationUnitSyntax unit)
    {
        Line($"// generated by goat-cs from {fileStem}.cs — edit the C# file");
        Line($"import {{ {Exports} }} from \"goat\";");
        var classes = new List<string>();
        foreach (var m in unit.Members.SelectMany(Flatten))
        {
            switch (m)
            {
                case ClassDeclarationSyntax c:
                    Class(c);
                    classes.Add(c.Identifier.Text);
                    break;
                case StructDeclarationSyntax s:
                    Struct(s);
                    classes.Add(s.Identifier.Text);
                    break;
                case EnumDeclarationSyntax e:
                    Enum(e);
                    classes.Add(e.Identifier.Text);
                    break;
                default:
                    throw new UnsupportedException(m, m.Kind().ToString());
            }
        }
        var main = classes.Contains(fileStem) ? fileStem : classes.FirstOrDefault();
        if (main != null) Line($"export default {main};");
        return sb.ToString();
    }

    static IEnumerable<MemberDeclarationSyntax> Flatten(MemberDeclarationSyntax m) => m switch
    {
        BaseNamespaceDeclarationSyntax ns => ns.Members.SelectMany(Flatten),
        _ => [m],
    };

    // ------------------------------------------------------------------ types
    void Enum(EnumDeclarationSyntax e)
    {
        Line($"export const {e.Identifier.Text} = Object.freeze({{");
        indent++;
        var next = 0L;
        foreach (var m in e.Members)
        {
            var v = m.EqualsValue != null ? Convert.ToInt64(model.GetConstantValue(m.EqualsValue.Value).Value) : next;
            Line($"{m.Identifier.Text}: {v},");
            next = v + 1;
        }
        indent--;
        Line("});");
    }

    void Struct(StructDeclarationSyntax s) => TypeBody(s.Identifier.Text, null, s.Members, s);

    void Class(ClassDeclarationSyntax c)
    {
        string? baseName = null;
        if (model.GetDeclaredSymbol(c) is INamedTypeSymbol t && t.BaseType is { SpecialType: not SpecialType.System_Object } b)
            baseName = b.Name;
        TypeBody(c.Identifier.Text, baseName, c.Members, c);
    }

    void TypeBody(string name, string? baseName, SyntaxList<MemberDeclarationSyntax> members, SyntaxNode node)
    {
        Line($"export class {name}{(baseName != null ? " extends " + baseName : "")} {{");
        indent++;
        foreach (var m in members)
        {
            switch (m)
            {
                case FieldDeclarationSyntax f:
                    var isStatic = f.Modifiers.Any(SyntaxKind.StaticKeyword) || f.Modifiers.Any(SyntaxKind.ConstKeyword);
                    foreach (var v in f.Declaration.Variables)
                    {
                        var init = v.Initializer != null ? Expr(v.Initializer.Value) : Default(model.GetTypeInfo(f.Declaration.Type).Type);
                        Line($"{(isStatic ? "static " : "")}{v.Identifier.Text} = {init};");
                    }
                    break;
                case PropertyDeclarationSyntax p:
                    Property(p);
                    break;
                case MethodDeclarationSyntax md:
                    Method(md);
                    break;
                case ConstructorDeclarationSyntax ctor:
                    Line($"constructor({Params(ctor.ParameterList)}) {{");
                    indent++;
                    if (baseName != null || ctor.Initializer is { ThisOrBaseKeyword.Text: "base" })
                        Line($"super({(ctor.Initializer != null ? Args(ctor.Initializer.ArgumentList) : "")});");
                    Body(ctor.Body, ctor.ExpressionBody);
                    indent--;
                    Line("}");
                    break;
                default:
                    throw new UnsupportedException(m, m.Kind().ToString());
            }
        }
        indent--;
        Line("}");
    }

    void Property(PropertyDeclarationSyntax p)
    {
        var isStatic = p.Modifiers.Any(SyntaxKind.StaticKeyword) ? "static " : "";
        var name = p.Identifier.Text;
        var auto = p.AccessorList != null && p.AccessorList.Accessors.All(a => a.Body == null && a.ExpressionBody == null);
        if (auto)
        {
            var init = p.Initializer != null ? Expr(p.Initializer.Value) : Default(model.GetTypeInfo(p.Type).Type);
            Line($"{isStatic}{name} = {init};");
            return;
        }
        if (p.ExpressionBody != null)
        {
            Line($"{isStatic}get {name}() {{ return {Expr(p.ExpressionBody.Expression)}; }}");
            return;
        }
        foreach (var a in p.AccessorList!.Accessors)
        {
            var get = a.Keyword.IsKind(SyntaxKind.GetKeyword);
            Line($"{isStatic}{(get ? "get" : "set")} {name}({(get ? "" : "value")}) {{");
            indent++;
            if (a.ExpressionBody != null) Line(get ? $"return {Expr(a.ExpressionBody.Expression)};" : $"{Expr(a.ExpressionBody.Expression)};");
            else Body(a.Body, null);
            indent--;
            Line("}");
        }
    }

    void Method(MethodDeclarationSyntax m)
    {
        var name = m.Identifier.Text;
        var sym = model.GetDeclaredSymbol(m)!;
        if (Lifecycle.TryGetValue(name, out var js) && m.ParameterList.Parameters.Count == 0) name = js;
        var isStatic = m.Modifiers.Any(SyntaxKind.StaticKeyword) ? "static " : "";
        var isAsync = m.Modifiers.Any(SyntaxKind.AsyncKeyword) ? "async " : "";
        // IEnumerator methods with `yield` are coroutines: JS generators
        var isIterator = sym.ReturnType is INamedTypeSymbol { Name: "IEnumerator" or "IEnumerable" } && m.DescendantNodes().OfType<YieldStatementSyntax>().Any();
        Line($"{isStatic}{isAsync}{(isIterator ? "*" : "")}{name}({Params(m.ParameterList)}) {{");
        indent++;
        Body(m.Body, m.ExpressionBody, !sym.ReturnsVoid);
        indent--;
        Line("}");
    }

    string Params(ParameterListSyntax p) => string.Join(", ", p.Parameters.Select(x =>
        x.Modifiers.Any(SyntaxKind.ParamsKeyword) ? "..." + x.Identifier.Text
        : x.Default != null ? $"{x.Identifier.Text} = {Expr(x.Default.Value)}"
        : x.Identifier.Text));

    void Body(BlockSyntax? body, ArrowExpressionClauseSyntax? arrow, bool returns = false)
    {
        if (body != null) foreach (var s in body.Statements) Statement(s);
        else if (arrow != null) Line(returns ? $"return {Expr(arrow.Expression)};" : $"{Expr(arrow.Expression)};");
    }

    // ------------------------------------------------------------------ statements
    void Block(StatementSyntax s)
    {
        indent++;
        if (s is BlockSyntax b) foreach (var x in b.Statements) Statement(x);
        else Statement(s);
        indent--;
    }

    void Statement(StatementSyntax s)
    {
        switch (s)
        {
            case BlockSyntax b:
                Line("{");
                Block(b);
                Line("}");
                break;
            case LocalDeclarationStatementSyntax l:
                var kw = l.IsConst ? "const" : "let";
                foreach (var v in l.Declaration.Variables)
                    Line($"{kw} {v.Identifier.Text}{(v.Initializer != null ? " = " + Expr(v.Initializer.Value) : " = " + Default(model.GetTypeInfo(l.Declaration.Type).Type))};");
                break;
            case ExpressionStatementSyntax e:
                Line(Expr(e.Expression) + ";");
                break;
            case ReturnStatementSyntax r:
                Line(r.Expression != null ? $"return {Expr(r.Expression)};" : "return;");
                break;
            case IfStatementSyntax i:
                Line($"if ({Expr(i.Condition)}) {{");
                Block(i.Statement);
                var els = i.Else;
                while (els != null)
                {
                    if (els.Statement is IfStatementSyntax ei)
                    {
                        Line($"}} else if ({Expr(ei.Condition)}) {{");
                        Block(ei.Statement);
                        els = ei.Else;
                    }
                    else
                    {
                        Line("} else {");
                        Block(els.Statement);
                        els = null;
                    }
                }
                Line("}");
                break;
            case WhileStatementSyntax w:
                Line($"while ({Expr(w.Condition)}) {{");
                Block(w.Statement);
                Line("}");
                break;
            case DoStatementSyntax d:
                Line("do {");
                Block(d.Statement);
                Line($"}} while ({Expr(d.Condition)});");
                break;
            case ForStatementSyntax f:
                var init = f.Declaration != null
                    ? "let " + string.Join(", ", f.Declaration.Variables.Select(v => $"{v.Identifier.Text} = {(v.Initializer != null ? Expr(v.Initializer.Value) : "0")}"))
                    : string.Join(", ", f.Initializers.Select(Expr));
                Line($"for ({init}; {(f.Condition != null ? Expr(f.Condition) : "")}; {string.Join(", ", f.Incrementors.Select(Expr))}) {{");
                Block(f.Statement);
                Line("}");
                break;
            case ForEachStatementSyntax fe:
                Line($"for (const {fe.Identifier.Text} of {Expr(fe.Expression)}) {{");
                Block(fe.Statement);
                Line("}");
                break;
            case BreakStatementSyntax:
                Line("break;");
                break;
            case ContinueStatementSyntax:
                Line("continue;");
                break;
            case ThrowStatementSyntax t:
                Line(t.Expression != null ? $"throw {Expr(t.Expression)};" : "throw __e;");
                break;
            case SwitchStatementSyntax sw:
                Line($"switch ({Expr(sw.Expression)}) {{");
                indent++;
                foreach (var sec in sw.Sections)
                {
                    foreach (var label in sec.Labels)
                    {
                        if (label is CaseSwitchLabelSyntax c) Line($"case {Expr(c.Value)}:");
                        else if (label is DefaultSwitchLabelSyntax) Line("default:");
                        else throw new UnsupportedException(label, "pattern case labels");
                    }
                    indent++;
                    foreach (var st in sec.Statements) Statement(st);
                    indent--;
                }
                indent--;
                Line("}");
                break;
            case TryStatementSyntax tr:
                Line("try {");
                Block(tr.Block);
                foreach (var c in tr.Catches)
                {
                    var id = c.Declaration?.Identifier.Text is { Length: > 0 } named ? named : "__e";
                    Line($"}} catch ({id}) {{");
                    Block(c.Block);
                }
                if (tr.Finally != null)
                {
                    Line("} finally {");
                    Block(tr.Finally.Block);
                }
                Line("}");
                break;
            case EmptyStatementSyntax:
                break;
            case YieldStatementSyntax y when y.IsKind(SyntaxKind.YieldReturnStatement):
                Line(y.Expression != null ? $"yield {Expr(y.Expression)};" : "yield null;");
                break;
            case YieldStatementSyntax:
                Line("return;");
                break;
            default:
                throw new UnsupportedException(s, s.Kind().ToString());
        }
    }

    // ------------------------------------------------------------------ expressions
    static bool IsVector(ITypeSymbol? t) => t is { Name: "Vector2" or "Vector3" } && t.ContainingNamespace?.Name == "GoatEngine";
    static bool IsEngine(ISymbol? s) => s?.ContainingNamespace is { Name: "GoatEngine" } || s?.ContainingType?.ContainingNamespace?.Name == "GoatEngine";
    static bool IsInteger(ITypeSymbol? t) => t?.SpecialType is SpecialType.System_Int32 or SpecialType.System_Int64 or SpecialType.System_Int16 or SpecialType.System_Byte or SpecialType.System_UInt32 or SpecialType.System_SByte or SpecialType.System_UInt16;
    static string Camel(string s) => s.Length > 2 && s.StartsWith("DO") && char.IsUpper(s[2]) ? "do" + s[2..] : s.Length == 0 ? s : char.ToLowerInvariant(s[0]) + s[1..];

    string Default(ITypeSymbol? t)
    {
        if (t == null) return "null";
        if (t.SpecialType == SpecialType.System_Boolean) return "false";
        if (t.SpecialType is >= SpecialType.System_Char and <= SpecialType.System_Double) return "0";
        if (IsVector(t) || t is { Name: "Quaternion" } && IsEngine(t)) return $"new {t.Name}()";
        if (t.TypeKind == TypeKind.Enum) return "0";
        if (t.TypeKind == TypeKind.Struct && t.Locations.Any(l => l.IsInSource) && t.ContainingNamespace?.Name != "GoatEngine") return $"new {t.Name}()";
        return "null";
    }

    /// The JS name of a member symbol.
    string MemberName(ISymbol s, string written)
    {
        if (IsEngine(s))
        {
            var key = $"{s.ContainingType?.Name}.{s.Name}";
            if (Renames.TryGetValue(key, out var r)) return r;
            if (s is IMethodSymbol) return Camel(s.Name);
            return s.Name;
        }
        if (s is IMethodSymbol m && Lifecycle.TryGetValue(m.Name, out var lc) && m.Parameters.Length == 0) return lc;
        if (s.ContainingType?.SpecialType == SpecialType.System_String || s.ContainingType?.Name == "Math" && s.ContainingNamespace?.Name == "System")
            return s.Name switch { "Length" => "length", "ToUpper" => "toUpperCase", "ToLower" => "toLowerCase", "Contains" => "includes", "StartsWith" => "startsWith", "EndsWith" => "endsWith", "Substring" => "substring", "IndexOf" => "indexOf", "Trim" => "trim", "Replace" => "replaceAll", "Split" => "split", _ => Camel(s.Name) };
        if (s.ContainingType is { Name: "List" or "IList" or "ICollection" or "IEnumerable" or "Array" } )
            return s.Name switch { "Count" or "Length" => "length", "Add" => "push", "Contains" => "includes", "IndexOf" => "indexOf", "Insert" => "splice", _ => Camel(s.Name) };
        return written;
    }

    string Args(ArgumentListSyntax a) => string.Join(", ", a.Arguments.Select(x => Expr(x.Expression)));

    /// `x` alone: `this.x` for instance members, `Type.x` for static ones.
    string Identifier(IdentifierNameSyntax id)
    {
        var s = model.GetSymbolInfo(id).Symbol;
        var text = id.Identifier.Text;
        if (s is IFieldSymbol or IPropertySymbol or IMethodSymbol && s.ContainingType != null && s.Kind != SymbolKind.Local)
        {
            var name = MemberName(s, text);
            return s.IsStatic ? $"{s.ContainingType.Name}.{name}" : $"this.{name}";
        }
        return text;
    }

    public string Expr(ExpressionSyntax e)
    {
        switch (e)
        {
            case LiteralExpressionSyntax l:
                return l.Kind() switch
                {
                    SyntaxKind.NumericLiteralExpression => Number(l),
                    SyntaxKind.StringLiteralExpression => SymbolDisplay.FormatLiteral(l.Token.ValueText, true),
                    SyntaxKind.CharacterLiteralExpression => SymbolDisplay.FormatLiteral(l.Token.ValueText, true),
                    SyntaxKind.NullLiteralExpression => "null",
                    SyntaxKind.TrueLiteralExpression => "true",
                    SyntaxKind.FalseLiteralExpression => "false",
                    SyntaxKind.DefaultLiteralExpression => Default(model.GetTypeInfo(l).ConvertedType),
                    _ => l.ToString(),
                };
            case IdentifierNameSyntax id:
                return Identifier(id);
            case ThisExpressionSyntax:
                return "this";
            case BaseExpressionSyntax:
                return "super";
            case ParenthesizedExpressionSyntax p:
                return $"({Expr(p.Expression)})";
            case MemberAccessExpressionSyntax m:
            {
                var s = model.GetSymbolInfo(m).Symbol;
                var target = model.GetSymbolInfo(m.Expression).Symbol;
                var left = target is INamedTypeSymbol nt ? nt.Name : Expr(m.Expression);
                if (s == null) return $"{left}.{m.Name.Identifier.Text}"; // dynamic
                if (s is IFieldSymbol { IsConst: true, ContainingType.TypeKind: not TypeKind.Enum } c && !IsEngine(c))
                    return Constant(c.ConstantValue);
                return $"{left}.{MemberName(s, m.Name.Identifier.Text)}";
            }
            case ConditionalAccessExpressionSyntax ca:
                return $"{Expr(ca.Expression)}?{ExprBinding(ca.WhenNotNull)}";
            case InvocationExpressionSyntax inv:
                return Invocation(inv);
            case ObjectCreationExpressionSyntax oc:
            {
                var t = model.GetTypeInfo(oc).Type;
                if (t is INamedTypeSymbol { Name: "List" or "HashSet" or "Queue" or "Stack" }) return oc.Initializer != null ? $"[{string.Join(", ", oc.Initializer.Expressions.Select(Expr))}]" : "[]";
                if (t is INamedTypeSymbol { Name: "Dictionary" }) return "new Map()";
                var args = oc.ArgumentList != null ? Args(oc.ArgumentList) : "";
                var created = $"new {t?.Name ?? oc.Type.ToString()}({args})";
                if (oc.Initializer is { } init)
                    return $"Object.assign({created}, {{ {string.Join(", ", init.Expressions.OfType<AssignmentExpressionSyntax>().Select(a => $"{a.Left}: {Expr(a.Right)}"))} }})";
                return created;
            }
            case ImplicitObjectCreationExpressionSyntax io:
            {
                var t = model.GetTypeInfo(io).Type;
                if (t is INamedTypeSymbol { Name: "List" or "HashSet" }) return "[]";
                if (t is INamedTypeSymbol { Name: "Dictionary" }) return "new Map()";
                return $"new {t?.Name}({Args(io.ArgumentList)})";
            }
            case AnonymousObjectCreationExpressionSyntax an:
                return "{ " + string.Join(", ", an.Initializers.Select(i => $"{(i.NameEquals?.Name.Identifier.Text ?? Expr(i.Expression))}: {Expr(i.Expression)}")) + " }";
            case ArrayCreationExpressionSyntax ac:
                return ac.Initializer != null ? $"[{string.Join(", ", ac.Initializer.Expressions.Select(Expr))}]" : $"new Array({Expr(ac.Type.RankSpecifiers[0].Sizes[0])}).fill({Default(((IArrayTypeSymbol)model.GetTypeInfo(ac).Type!).ElementType)})";
            case ImplicitArrayCreationExpressionSyntax iac:
                return $"[{string.Join(", ", iac.Initializer.Expressions.Select(Expr))}]";
            case CollectionExpressionSyntax ce:
                return $"[{string.Join(", ", ce.Elements.OfType<ExpressionElementSyntax>().Select(x => Expr(x.Expression)))}]";
            case InitializerExpressionSyntax ie:
                return $"[{string.Join(", ", ie.Expressions.Select(Expr))}]";
            case ElementAccessExpressionSyntax ea:
            {
                var t = model.GetTypeInfo(ea.Expression).Type;
                if (t is INamedTypeSymbol { Name: "Dictionary" }) return $"{Expr(ea.Expression)}.get({Args(ea.ArgumentList.Arguments.Count > 0 ? SyntaxFactory.ArgumentList(ea.ArgumentList.Arguments) : SyntaxFactory.ArgumentList())})";
                return $"{Expr(ea.Expression)}[{string.Join(", ", ea.ArgumentList.Arguments.Select(a => Expr(a.Expression)))}]";
            }
            case BinaryExpressionSyntax b:
                return Binary(b);
            case AssignmentExpressionSyntax a:
                return Assignment(a);
            case PrefixUnaryExpressionSyntax pu:
                if (pu.IsKind(SyntaxKind.UnaryMinusExpression) && IsVector(model.GetTypeInfo(pu.Operand).Type)) return $"{Expr(pu.Operand)}.mul(-1)";
                return pu.OperatorToken.Text + Expr(pu.Operand);
            case PostfixUnaryExpressionSyntax po:
                if (po.IsKind(SyntaxKind.SuppressNullableWarningExpression)) return Expr(po.Operand);
                return Expr(po.Operand) + po.OperatorToken.Text;
            case ConditionalExpressionSyntax c:
                return $"({Expr(c.Condition)} ? {Expr(c.WhenTrue)} : {Expr(c.WhenFalse)})";
            case CastExpressionSyntax cast:
            {
                var to = model.GetTypeInfo(cast.Type).Type;
                var inner = Expr(cast.Expression);
                return IsInteger(to) && !IsInteger(model.GetTypeInfo(cast.Expression).Type) ? $"Math.trunc({inner})" : inner;
            }
            case InterpolatedStringExpressionSyntax isx:
            {
                var sb2 = new StringBuilder("`");
                foreach (var part in isx.Contents)
                {
                    if (part is InterpolatedStringTextSyntax t) sb2.Append(t.TextToken.ValueText.Replace("\\", "\\\\").Replace("`", "\\`").Replace("${", "\\${"));
                    else if (part is InterpolationSyntax i)
                    {
                        var v = Expr(i.Expression);
                        if (i.FormatClause != null && i.FormatClause.FormatStringToken.ValueText is var f && f.StartsWith('F') && int.TryParse(f[1..], out var digits))
                            v = $"({v}).toFixed({digits})";
                        sb2.Append("${").Append(v).Append('}');
                    }
                }
                return sb2.Append('`').ToString();
            }
            case AwaitExpressionSyntax aw:
                return $"(await {Expr(aw.Expression)})";
            case SimpleLambdaExpressionSyntax sl:
                return $"{(sl.AsyncKeyword.IsKind(SyntaxKind.AsyncKeyword) ? "async " : "")}({sl.Parameter.Identifier.Text}) => {LambdaBody(sl.Body)}";
            case ParenthesizedLambdaExpressionSyntax pl:
                return $"{(pl.AsyncKeyword.IsKind(SyntaxKind.AsyncKeyword) ? "async " : "")}({string.Join(", ", pl.ParameterList.Parameters.Select(p => p.Identifier.Text))}) => {LambdaBody(pl.Body)}";
            case IsPatternExpressionSyntax ip when ip.Pattern is ConstantPatternSyntax { Expression: LiteralExpressionSyntax { RawKind: (int)SyntaxKind.NullLiteralExpression } }:
                return $"({Expr(ip.Expression)} == null)";
            case IsPatternExpressionSyntax ip when ip.Pattern is UnaryPatternSyntax { Pattern: ConstantPatternSyntax { Expression: LiteralExpressionSyntax { RawKind: (int)SyntaxKind.NullLiteralExpression } } }:
                return $"({Expr(ip.Expression)} != null)";
            default:
                break;
        }
        throw new UnsupportedException(e, e.Kind().ToString());
    }

    string ExprBinding(ExpressionSyntax e) => e switch
    {
        MemberBindingExpressionSyntax mb => "." + (model.GetSymbolInfo(mb).Symbol is { } s ? MemberName(s, mb.Name.Identifier.Text) : mb.Name.Identifier.Text),
        InvocationExpressionSyntax { Expression: MemberBindingExpressionSyntax mb } inv => ExprBinding(mb) + $"({Args(inv.ArgumentList)})",
        MemberAccessExpressionSyntax ma => ExprBinding(ma.Expression) + "." + ma.Name.Identifier.Text,
        _ => throw new UnsupportedException(e, "?. on " + e.Kind()),
    };

    string LambdaBody(CSharpSyntaxNode body)
    {
        if (body is ExpressionSyntax x) return Expr(x);
        var saved = sb.Length;
        var savedIndent = indent;
        indent = 1;
        Line("{");
        Block((BlockSyntax)body);
        Line("}");
        var text = sb.ToString(saved, sb.Length - saved).TrimEnd();
        sb.Length = saved;
        indent = savedIndent;
        return text;
    }

    string Number(LiteralExpressionSyntax l)
    {
        var v = l.Token.Value;
        return v switch
        {
            float f => f.ToString("R", System.Globalization.CultureInfo.InvariantCulture),
            double d => d.ToString("R", System.Globalization.CultureInfo.InvariantCulture),
            decimal m => m.ToString(System.Globalization.CultureInfo.InvariantCulture),
            _ => Convert.ToString(v, System.Globalization.CultureInfo.InvariantCulture) ?? "0",
        };
    }

    static string Constant(object? v) => v switch
    {
        null => "null",
        string s => SymbolDisplay.FormatLiteral(s, true),
        bool b => b ? "true" : "false",
        float f => f.ToString("R", System.Globalization.CultureInfo.InvariantCulture),
        double d => d.ToString("R", System.Globalization.CultureInfo.InvariantCulture),
        _ => Convert.ToString(v, System.Globalization.CultureInfo.InvariantCulture) ?? "0",
    };

    string Invocation(InvocationExpressionSyntax inv)
    {
        var s = model.GetSymbolInfo(inv).Symbol as IMethodSymbol;
        var args = Args(inv.ArgumentList);
        if (inv.Expression is IdentifierNameSyntax { Identifier.Text: "nameof" })
            return SymbolDisplay.FormatLiteral(inv.ArgumentList.Arguments[0].ToString().Split('.').Last(), true);
        if (s != null)
        {
            var on = inv.Expression is MemberAccessExpressionSyntax ma ? Expr(ma.Expression) : null;
            // collections and strings
            if (s.ContainingType is { Name: "List" })
            {
                switch (s.Name)
                {
                    case "Remove": return $"((l, x) => {{ const i = l.indexOf(x); if (i >= 0) l.splice(i, 1); return i >= 0; }})({on}, {args})";
                    case "RemoveAt": return $"{on}.splice({args}, 1)";
                    case "Clear": return $"({on}.length = 0)";
                    case "Insert": return $"{on}.splice({Expr(inv.ArgumentList.Arguments[0].Expression)}, 0, {Expr(inv.ArgumentList.Arguments[1].Expression)})";
                    case "AddRange": return $"{on}.push(...{args})";
                }
            }
            if (s.ContainingType is { Name: "Dictionary" })
            {
                switch (s.Name)
                {
                    case "Add": return $"{on}.set({args})";
                    case "ContainsKey": return $"{on}.has({args})";
                    case "Remove": return $"{on}.delete({args})";
                    case "Clear": return $"{on}.clear()";
                }
            }
            if (s.Name == "ToString" && s.Parameters.Length == 0 && on != null) return $"String({on})";
            if (s.ContainingType is { Name: "Console" } && s.Name.StartsWith("Write")) return $"Debug.log({args})";
            if (s.ContainingType?.SpecialType == SpecialType.System_Single || s.ContainingType?.SpecialType == SpecialType.System_Int32)
            {
                if (s.Name == "Parse") return $"Number({args})";
            }
        }
        return $"{Expr(inv.Expression)}({args})";
    }

    string Binary(BinaryExpressionSyntax b)
    {
        var lt = model.GetTypeInfo(b.Left).Type;
        var rt = model.GetTypeInfo(b.Right).Type;
        var l = Expr(b.Left);
        var r = Expr(b.Right);
        var op = b.OperatorToken.Text;
        if (IsVector(lt) || IsVector(rt))
        {
            switch (op)
            {
                case "+": return $"{l}.add({r})";
                case "-": return $"{l}.sub({r})";
                case "*": return IsVector(lt) ? $"{l}.mul({r})" : $"{r}.mul({l})";
                case "/": return $"{l}.mul(1 / ({r}))";
            }
        }
        if (op == "/" && IsInteger(lt) && IsInteger(rt)) return $"Math.trunc({l} / {r})";
        if (op == "==") op = "===";
        if (op == "!=") op = "!==";
        if (b.IsKind(SyntaxKind.AsExpression)) return l;
        if (b.IsKind(SyntaxKind.IsExpression)) return $"({l} instanceof {r})";
        return $"{l} {op} {r}";
    }

    string Assignment(AssignmentExpressionSyntax a)
    {
        var lt = model.GetTypeInfo(a.Left).Type;
        var l = Expr(a.Left);
        var r = Expr(a.Right);
        if (a.Left is ElementAccessExpressionSyntax ea && model.GetTypeInfo(ea.Expression).Type is INamedTypeSymbol { Name: "Dictionary" })
            return $"{Expr(ea.Expression)}.set({Expr(ea.ArgumentList.Arguments[0].Expression)}, {r})";
        if (IsVector(lt))
        {
            switch (a.OperatorToken.Text)
            {
                case "+=": return $"{l} = {l}.add({r})";
                case "-=": return $"{l} = {l}.sub({r})";
                case "*=": return $"{l} = {l}.mul({r})";
                case "/=": return $"{l} = {l}.mul(1 / ({r}))";
            }
        }
        if (a.OperatorToken.Text == "/=" && IsInteger(lt)) return $"{l} = Math.trunc({l} / {r})";
        return $"{l} {a.OperatorToken.Text} {r}";
    }
